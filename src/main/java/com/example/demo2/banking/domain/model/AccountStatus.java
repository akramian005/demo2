package com.example.demo2.banking.domain.model;

public enum AccountStatus {

    /**
     * Обычный рабочий статус — доступны debit/credit.
     */
    ACTIVE,

    /**
     * Заморожен (служба безопасности, подозрение на мошенничество,
     * или клиент сам временно заблокировал). Операции запрещены,
     * но счёт можно снова активировать через activate().
     */
    FROZEN,

    /**
     * Закрыт окончательно. Открыть заново нельзя —
     * если понадобится, клиент открывает новый счёт.
     * По правилам close() нельзя закрыть с положительным балансом.
     */
    CLOSED
}